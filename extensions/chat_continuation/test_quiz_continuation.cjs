const assert = require('node:assert/strict');
const core = require('./continuation.cjs');
const emitted = (id, question, turn) => ({type:'content',turn_id:turn,metadata:{call_kind:'quiz_question_emitted',question_index:0,qa_pair:{question_id:id,question,question_type:'choice',options:{A:'a',B:'b'},correct_answer:'A',explanation:'e'}}});
const snapshot = {capability:'deep_question',enabledTools:['rag'],knowledgeBases:['original-kb'],llmSelection:{profile_id:'original-model'},config:{mode:'custom',num_questions:10,difficulty:'',question_types:[],per_type_counts:{}},attachments:[{type:'pdf',filename:'original.pdf'}]};
const user = {id:1,role:'user',content:'Generate 10 original questions',requestSnapshot:snapshot};
const answer = {id:2,role:'assistant',capability:'deep_question',content:'Original introduction',parentMessageId:1,events:[emitted('q_1','First question','turn-first')]};
const first = core.target([user,answer],{mode:'custom',num_questions:10});
assert(first,'Quiz must offer continuation');
assert.equal(first.remaining,9);
const request = core.request(first);
assert.equal(request.snapshot.capability,'deep_question');
assert.equal(request.snapshot.config.num_questions,9);
assert.equal(request.snapshot.llmSelection,snapshot.llmSelection);
assert.equal(request.snapshot.knowledgeBases,snapshot.knowledgeBases);
assert.deepEqual(request.snapshot.attachments,snapshot.attachments);
assert(request.text.includes('First question'),'Include unanswered existing questions to avoid repeats');
assert.equal(snapshot.config.num_questions,10,'Original snapshot is immutable');
const control = {id:3,role:'user',content:request.text,parentMessageId:2,requestSnapshot:request.snapshot};
const more = {id:4,role:'assistant',capability:'deep_question',content:'Additional introduction',parentMessageId:3,events:[emitted('q_1','Second question','turn-next')]};
const rows=[user,answer,control,more];
const merged=core.merge(rows);
assert.equal(merged.length,2);
assert.deepEqual(core.quizSegments(merged[1]).map(s=>s.id),[2,4]);
assert.deepEqual(core.quizSegments(merged[1]).map(s=>s.events[0].turn_id),['turn-first','turn-next']);
assert.equal(core.target(rows).remaining,8,'Persisted total survives reload and remaining snapshot');
assert.deepEqual(core.merge(JSON.parse(JSON.stringify(rows))),merged);
const performance={id:5,role:'user',content:'[Quiz Performance]\n1. q_1 answered',parentMessageId:4};
assert.equal(core.target([...rows,performance]).remaining,8);
assert.equal(core.target([...rows,performance]).parentMessageId,5,'Keep the answer-record branch in the continuation path');
assert.equal(core.target([...rows,{...performance,content:'New question'}]),null);
const oldWrong={...user,requestSnapshot:{...snapshot,config:{...snapshot.config,num_questions:1}}};
assert.equal(core.target([oldWrong,answer],{mode:'custom',num_questions:10}).remaining,9,'Confirmed panel repairs legacy lost count');
const results={type:'result',turn_id:'turn-first',metadata:{summary:{results:[{qa_pair:answer.events[0].metadata.qa_pair}]}}};
assert.equal(core.quizQuestions({...answer,events:[...answer.events,results]}).length,1,'Summary and streamed cards must not double count');
const failed={...more,content:'',events:[{type:'error',metadata:{turn_terminal:true,status:'failed'}}]};
assert.equal(core.target([user,answer,control,failed]).remaining,9,'Failure with no additional cards retains prefix');
const full={...answer,events:Array.from({length:10},(_,i)=>emitted('q_'+(i+1),'Question '+i,'turn-first'))};
assert.equal(core.target([user,full]).remaining,10,'Completed quiz can add another batch');
const chat=core.target([{...user,requestSnapshot:{capability:'chat'}},{...answer,capability:'chat',content:'Text',events:[{type:'error',metadata:{turn_terminal:true,status:'failed'}}]}]);
assert(core.request(chat).text.includes('[DeepTutor continue v1:2]'));
console.log('PASS: quiz remaining count, legacy confirmed count, persisted grouping/reload, independent turn IDs, immutable original snapshot, performance branch and failed continuation');
